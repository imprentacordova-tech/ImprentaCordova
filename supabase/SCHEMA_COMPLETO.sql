-- Cálculo de balance del libro financiero
CREATE OR REPLACE FUNCTION get_ledger_balance()
RETURNS TABLE (ingresos NUMERIC, egresos NUMERIC, total NUMERIC) AS $$
BEGIN
  RETURN QUERY
  SELECT
    COALESCE(SUM(amount) FILTER (WHERE type = 'income'), 0.00)::NUMERIC AS ingresos,
    COALESCE(SUM(amount) FILTER (WHERE type = 'expense'), 0.00)::NUMERIC AS egresos,
    (COALESCE(SUM(amount) FILTER (WHERE type = 'income'), 0.00) - COALESCE(SUM(amount) FILTER (WHERE type = 'expense'), 0.00))::NUMERIC AS total
  FROM financial_ledger;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Secuencial atómico para facturación electrónica por año
CREATE OR REPLACE FUNCTION next_invoice_number()
RETURNS integer AS $$
DECLARE
  current_year text;
  next_val integer;
BEGIN
  current_year := to_char(now(), 'YYYY');
  IF NOT EXISTS (SELECT 1 FROM pg_sequences WHERE sequencename = 'invoice_seq_' || current_year) THEN
    EXECUTE format('CREATE SEQUENCE invoice_seq_%s START 1', current_year);
  END IF;
  EXECUTE format('SELECT nextval(''invoice_seq_%s'')', current_year) INTO next_val;
  RETURN next_val;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Obtener rol del usuario autenticado
CREATE OR REPLACE FUNCTION get_user_role()
RETURNS text AS $$
  SELECT COALESCE(
    (SELECT rol FROM users WHERE id::text = auth.uid()::text),
    'Operador'
  );
$$ LANGUAGE sql SECURITY DEFINER STABLE;

