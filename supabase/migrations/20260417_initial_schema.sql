
-- SCHEMA INITIALIZATION FOR IMPRENTA CORDOVA
-- FECHA: 2026-04-17
-- PRIORIDAD: VELOCIDAD Y TRAZABILIDAD (REGULACIONES SRI)

-- 1. Habilitar extensiones necesarias
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Tabla de Clientes
CREATE TABLE clientes (
    id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    cedula TEXT NOT NULL,
    ruc TEXT,
    nombre TEXT NOT NULL,
    nombre_comercial TEXT,
    actividades TEXT,
    direccion TEXT,
    notas TEXT,
    telefono TEXT[] DEFAULT '{}',
    email TEXT,
    creado_en TIMESTAMPTZ DEFAULT now(),
    regimen TEXT DEFAULT 'General',
    establecimiento_predeterminado TEXT,
    punto_emision_predeterminado TEXT,
    num_establecimientos_open INTEGER DEFAULT 0
);

-- 3. Tabla de Productos/Catálogo
CREATE TABLE productos (
    id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    precio NUMERIC(12, 2) DEFAULT 0.00,
    categoria TEXT,
    es_sri BOOLEAN DEFAULT false,
    imagen_url TEXT,
    specs TEXT[] DEFAULT '{}',
    unit TEXT,
    is_popular BOOLEAN DEFAULT false
);

-- 4. Tabla de Trabajos (Ordenes de Producción)
CREATE TABLE trabajos (
    id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    orden INTEGER GENERATED BY DEFAULT AS IDENTITY,
    cliente_id TEXT REFERENCES clientes(id) ON DELETE SET NULL,
    titular TEXT,
    tipo TEXT DEFAULT 'general',
    subtipo TEXT,
    cantidad INTEGER DEFAULT 1,
    tamano TEXT,
    total NUMERIC(12, 2) DEFAULT 0.00,
    abono NUMERIC(12, 2) DEFAULT 0.00,
    saldo NUMERIC(12, 2) DEFAULT 0.00,
    estado TEXT DEFAULT 'Pendiente',
    fecha_entrada TIMESTAMPTZ DEFAULT now(),
    fecha_entrega TIMESTAMPTZ,
    tiempo_entrega_estimado TEXT,
    caduco BOOLEAN DEFAULT false,
    foto_original_url TEXT,
    creado_por TEXT,
    actualizado_por TEXT,
    establecimiento TEXT,
    punto_emision TEXT,
    clave_acceso TEXT,
    estado_clave TEXT DEFAULT 'PENDIENTE',
    imprimir_clave BOOLEAN DEFAULT true,
    origen TEXT DEFAULT 'Interno',
    es_renovacion BOOLEAN DEFAULT false,
    prioridad TEXT DEFAULT 'Normal',
    historial JSONB DEFAULT '[]'::jsonb,
    fecha_vencimiento TIMESTAMPTZ,
    actividad_seleccionada TEXT,
    arte_aprobado BOOLEAN DEFAULT false
);

-- 5. Tabla de Inventario
CREATE TABLE inventario (
    id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    item TEXT NOT NULL,
    cantidad NUMERIC(12, 4) DEFAULT 0.00,
    unidad TEXT,
    costo_unitario NUMERIC(12, 4) DEFAULT 0.00,
    minimo NUMERIC(12, 2) DEFAULT 0.00
);

-- 6. Tabla de Proveedores
CREATE TABLE proveedores (
    id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    nombre TEXT NOT NULL,
    categoria TEXT,
    tipo TEXT,
    contacto TEXT,
    telefono TEXT,
    email TEXT,
    website TEXT,
    direccion TEXT,
    ciudad TEXT,
    productos TEXT,
    notas TEXT,
    estado TEXT DEFAULT 'Activo',
    creado_en TIMESTAMPTZ DEFAULT now()
);

-- 7. Tabla de Credenciales SRI (Seguridad)
CREATE TABLE sri_credentials (
    ruc TEXT PRIMARY KEY,
    password TEXT,
    origen TEXT,
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- 8. Tabla de Usuarios
CREATE TABLE users (
    id TEXT PRIMARY KEY DEFAULT uuid_generate_v4()::text,
    nombre TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    rol TEXT DEFAULT 'Operador',
    estado TEXT DEFAULT 'Activo',
    ultimo_acceso TIMESTAMPTZ,
    require_password BOOLEAN DEFAULT false
);

-- 9. POLÍTICAS DE SEGURIDAD (RLS)
ALTER TABLE clientes ENABLE ROW LEVEL SECURITY;
ALTER TABLE trabajos ENABLE ROW LEVEL SECURITY;
ALTER TABLE productos ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventario ENABLE ROW LEVEL SECURITY;
ALTER TABLE proveedores ENABLE ROW LEVEL SECURITY;
ALTER TABLE sri_credentials ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;

-- Nota: Para simplificar el desarrollo inicial según el perfil de "Velocidad sobre Burocracia", 
-- se crean políticas que permiten acceso total. Se deben restringir en Fase 2 (Seguridad RBAC).

CREATE POLICY "Allow everything for now" ON clientes FOR ALL USING (true);
CREATE POLICY "Allow everything for now" ON trabajos FOR ALL USING (true);
CREATE POLICY "Allow everything for now" ON productos FOR ALL USING (true);
CREATE POLICY "Allow everything for now" ON inventario FOR ALL USING (true);
CREATE POLICY "Allow everything for now" ON proveedores FOR ALL USING (true);
CREATE POLICY "Allow everything for now" ON sri_credentials FOR ALL USING (true);
CREATE POLICY "Allow everything for now" ON users FOR ALL USING (true);

-- 10. INDEXACIÓN BÁSICA
CREATE INDEX idx_trabajos_cliente_id ON trabajos(cliente_id);
CREATE INDEX idx_trabajos_estado ON trabajos(estado);
CREATE INDEX idx_clientes_cedula ON clientes(cedula);
CREATE INDEX idx_inventario_item ON inventario(item);
